//! Péchoux, 2026): classical control with unbounded loops around quantum
//! kernels. It checks well-formedness, splits the program into kernels and
//! host code, optimizes the kernels, emits OpenQASM 3, and runs the program
//! exactly on cq-states (Feng and Ying, 2021) for termination and costs.
//! Roop programs with qubits come in through `lower_roop`.

